class AliasReplace(BaseModel):
    """整组替换一个简称对应的正式保管方；空列表即注销该简称。"""

    model_config = ConfigDict(extra="forbid")

    formal_parties: list[str] = Field(
        description="该简称对应的全部正式保管方（整组替换，顺序即返回顺序）"
    )

    @field_validator("formal_parties")
    @classmethod
    def _strip_and_dedup(cls, values: list[str]) -> list[str]:
        cleaned: list[str] = []
        for value in values:
            name = value.strip()
            if not name:
                raise ValueError("formal party names must not be empty")
            if name not in cleaned:
                cleaned.append(name)
        return cleaned


class AliasView(BaseModel):
    alias: str
    formal_parties: list[str]
    dictionary_revision: int


class AliasListResponse(BaseModel):
    dictionary_revision: int
    aliases: list[AliasView]


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #
def utcnow_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def to_utc_iso(dt: datetime) -> str:
    """Normalize any timezone-aware datetime to a fixed-width UTC ISO string."""
    return dt.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%fZ")


def canonical_payload(entry: ScanEntry) -> dict:
    """Deterministic representation used to detect same-revision divergence."""
    if entry.event_type == "WITHDRAWAL":
        return {"event_type": "WITHDRAWAL"}
    return {
        "event_type": "HANDOVER",
        "ts_utc": to_utc_iso(entry.ts_utc),  # type: ignore[arg-type]
        "giver": entry.giver,
        "receiver": entry.receiver,
    }


def payload_hash_of(payload: dict) -> str:
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(blob).hexdigest()


def entry_payload_hash(entry: ScanEntry) -> str:
    return payload_hash_of(canonical_payload(entry))
